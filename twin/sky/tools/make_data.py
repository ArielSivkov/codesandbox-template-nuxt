def ra_deg(s):
    m = re.match(r'(\d+)h (\d+)m ([\d.]+)s', s); h, mi, se = m.groups(); return (int(h) + int(mi) / 60 + float(se) / 3600) * 15
def dec_deg(s):
    m = re.match(r'([+-])(\d+)° (\d+)′ (\d+)″', s); sg, d, mi, se = m.groups(); v = int(d) + int(mi) / 60 + int(se) / 3600; return -v if sg == '-' else v
rows = []
for s in bsc:
    if 'Vmag' not in s or 'RA' not in s or 'Dec' not in s: continue
    rows.append(s)
rows.sort(key=lambda s: float(s['Vmag']))
sel = rows[:300]
lines = []
for s in sel:
    nm = names.get(s['HR'], '')
    he = HE.get(nm, '')
    bv = float(s['B-V']) if s.get('B-V') else 0.6
    lines.append('[%s,%.5f,%.5f,%s,%s,%d,%d,%s,%s,%s]' % (s['HR'], ra_deg(s['RA']), dec_deg(s['Dec']), float(s['Vmag']), bv,
        round(float(s.get('pmRA', 0)) * 1000), round(float(s.get('pmDE', 0)) * 1000), json.dumps(nm), json.dumps(he, ensure_ascii=False), json.dumps(s.get('Name', '').strip())))
