T = json.load(open(os.path.join(ROOT, 'tools/tables_full.json')))
EPS, TMAX = 1e-6, 3.0          # keep VSOP term if A·TMAX^k ≥ EPS (rad or AU)  -> truncation error ≤ ~4" (tools/trunc_study.py)
out = ['/* GENERATED by tools/make_data.py — do not edit.',
       ' * VSOP87D (heliocentric, ecliptic & equinox of date, TDB, tau = Julian millennia from J2000)',
       ' * Bretagnon P., Francou G. (1988) A&A 202, 309. Data: IMCCE / CDS VizieR VI/81 (free scientific data).',
       ' * Numbers taken from the full VSOP87D tables as shipped (as data literals) in the PyMeeus package;',
       ' * truncated here: term kept if A*3^k >= 1e-6 (rad | AU). Measured truncation error vs. full series:',
       ' * <= 4.4 arcsec geocentric, years -1000..2100 (tools/trunc_study.py).',
       ' * Layout: VSOP[planet][coord][k] = flat [A, B, C, A, B, C, ...], A in 1e-8 units. */',
       'export const VSOP = {']
n = 0
for p in ['Mercury', 'Venus', 'Earth', 'Mars', 'Jupiter', 'Saturn']:
    parts = []
    for c in 'LBR':
        ser = []
        for k, terms in enumerate(T[p][c]):
            keep = [t for t in terms if t[0] * 1e-8 * TMAX ** k >= EPS]
            n += len(keep)
            ser.append('[' + ','.join('%s,%s,%s' % (repr(round(a, 3)).rstrip('0').rstrip('.') if a != int(a) else str(int(a)), repr(b), repr(cc)) for a, b, cc in keep) + ']')
        parts.append('%s:[%s]' % (c, ','.join(ser)))
    out.append('  %s:{%s},' % (p, ','.join(parts)))
out.append('};')
out.append('export const VSOP_TERMS = %d;' % n)
open(os.path.join(ROOT, 'src/data/vsop87d.js'), 'w').write('\n'.join(out) + '\n')
print('vsop terms', n)
# Moon: Meeus table 47.A (D, M, M', F, Σl [1e-6 deg], Σr [1e-3 km]) and 47.B (D, M, M', F, Σb [1e-6 deg])
lr = [x[:4] + [int(x[4]), int(x[5])] for x in T['moonLR']]
b = [x[:4] + [int(x[4])] for x in T['moonB']]
nut_a = T['nut']['NUTATION_ARG_TABLE']; nut_s = T['nut']['NUTATION_SINE_COEF_TABLE']; nut_c = T['nut']['NUTATION_COSINE_COEF_TABLE']
nut = []
for i in range(len(nut_a)):
    s = nut_s[i]; c = nut_c[i] if i < len(nut_c) else [0.0, 0.0]
    nut.append(nut_a[i] + [s[0], s[1], c[0], c[1]])
