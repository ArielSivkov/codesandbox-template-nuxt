// Dependency-free bundler (same scheme as swarm/physics/tools/build.mjs):
// src/**/*.js (ES modules) → dist/esh27-sky.js (plain script → window.ESH27Sky) + dist/esh27-sky.mjs.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const order = ['data/vsop87d', 'data/moon47', 'data/bsc300', 'time', 'sky', 'hebrew', 'zmanim', 'calib', 'state'];
const key = m => m.replace(/\W/g, '_');
let body = ''; const top = [];
for (const m of order) {
  let src = readFileSync(join(root, 'src', m + '.js'), 'utf8'); const names = [];
  src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w/]+)\.js';?\s*$/gm, (_, list, from) => `const {${list.replace(/\bas\b/g, ':')}} = __m.${key(from)};`);
  src = src.replace(/^export\s*\{([^}]*)\};?\s*$/gm, (_, list) => { for (const x of list.split(',').map(s => s.trim()).filter(Boolean)) names.push(x); return ''; });
  src = src.replace(/^export\s+(function|const|let|class)\s+(\w+)/gm, (_, kw, name) => { names.push(name); return `${kw} ${name}`; });
  if (/^export\s+const\s+\w+\s*=[^;\n]*,\s*\w+\s*=/m.test(src)) throw new Error('multi-name export const in ' + m);
  if (/^export\s/m.test(src) || /^import\s/m.test(src)) throw new Error('unhandled import/export in ' + m);
  body += `\n// ===== src/${m}.js\n__m.${key(m)} = (function () {\n${src}\nreturn { ${[...new Set(names)].join(', ')} };\n})();\n`;
  if (!m.startsWith('data/') && m !== 'hebrew') top.push(...names);
}
const version = (readFileSync(join(root, 'src/index.js'), 'utf8').match(/VERSION = '([^']+)'/) || [])[1];
const banner = `/* ESH27 twin sky & time ${version} — generated by tools/build.mjs from src/. Do not edit.\n * Data: VSOP87D (Bretagnon & Francou 1988), Meeus AA ch.47/22, Yale BSC5 (public domain). */\n`;
const core = `const __m = {};\n${body}\nconst __api = Object.assign({ VERSION: '${version}', hebrew: __m.hebrew }, __m.time, __m.sky, __m.zmanim, __m.calib, __m.state);\n`;
const out = {
  'dist/esh27-sky.js': banner + `(function (G) {\n'use strict';\n${core}G.ESH27Sky = __api;\nif (typeof module !== 'undefined' && module.exports) module.exports = __api;\n})(typeof window !== 'undefined' ? window : globalThis);\n`,
  'dist/esh27-sky.mjs': banner + core + `export default __api;\nexport const { ${[...new Set(top)].join(', ')} } = __api;\nexport const hebrew = __api.hebrew;\nexport const VERSION = __api.VERSION;\n`,
};
// --check: לא כותב; נכשל אם dist לא נבנה מחדש אחרי שינוי ב-src (משמש את twin/integration/tools/ci.sh)
if (process.argv.includes('--check')) {
  const stale = Object.keys(out).filter(f => { try { return readFileSync(join(root, f), 'utf8') !== out[f]; } catch (e) { return true; } });
  console.log(stale.length ? 'dist לא עדכני מול src: ' + stale.join(', ') + ' (להריץ node sky/tools/build.mjs)' : 'dist עדכני מול src (' + Object.keys(out).length + ' קבצים)');
  process.exit(stale.length ? 1 : 0);
}
mkdirSync(join(root, 'dist'), { recursive: true });
for (const f in out) writeFileSync(join(root, f), out[f]);
console.log('built', new Set(top).size, 'exports,', readFileSync(join(root, 'dist/esh27-sky.js')).length, 'bytes');
